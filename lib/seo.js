function renderSitemap() {
  const url = (loc, changefreq, priority) => `  <url><loc>${SITE}${loc}</loc><changefreq>${changefreq}</changefreq><priority>${priority}</priority></url>`;
  // trip pages stay out on purpose: a share code is the privacy boundary, and
  // robots.txt disallows /trip/ — listing them here would contradict that
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${url('/', 'weekly', '1.0')}
${url('/plan', 'monthly', '0.8')}
${url('/terms', 'yearly', '0.3')}
${url('/privacy', 'yearly', '0.3')}
${url('/accessibility', 'yearly', '0.3')}
${url('/destinations', 'weekly', '0.9')}
${[...Object.values(AUDIENCES), AI_PAGE].map((a) => url(`/${a.slug}`, 'monthly', '0.9')).join('\n')}
${DESTINATIONS.map((d) => url(`/destinations/${d.slug}`, 'monthly', '0.7')).join('\n')}
</urlset>
`;
}

